import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { openTraining } from '../../src/training/workout';
import { upperStarter } from '../../src/training/routines';
import { openNodeDatabase } from './node-database';

test('equipment selection preserves checked assignments and entries across reopening', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ultra-equipment-'));
  const path = join(directory, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  t.after(async () => { await training.close(); await rm(directory, { recursive: true, force: true }); });
  await training.start(upperStarter);
  const exercise = training.getSnapshot().workout!.exercises[0];
  const a = await training.createEquipmentSetup({ label: 'Tower A', gym: null, ratio: null });
  const b = await training.createEquipmentSetup({ label: 'Tower B', gym: 'Gym', ratio: '2:1' });
  await training.selectEquipmentSetup(exercise.id, a.id);
  await training.editSet(exercise.sets[0].id, { load: '40', reps: '6' });
  await training.setPerformed(exercise.sets[0].id, true);
  await training.editSet(exercise.sets[1].id, { load: '35', reps: '8' });
  await training.selectEquipmentSetup(exercise.id, b.id);
  await training.archiveEquipmentSetup(a.id, true);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  const recovered = training.getSnapshot().workout!.exercises[0];
  assert.deepEqual(recovered.sets.slice(0, 2).map(s => [s.equipmentSetupId, s.load, s.reps, s.performed]), [[a.id, '40', '6', true], [b.id, '35', '8', false]]);
  assert.equal(training.getSnapshot().equipmentSetups.find(s => s.id === a.id)!.ratio, null);
  assert.equal(training.getSnapshot().equipmentSetups.find(s => s.id === a.id)!.archived, true);
  await training.archiveEquipmentSetup(a.id, false);
  await training.correctSetEquipment(exercise.sets[0].id, null);
  await training.selectEquipmentSetup(exercise.id, null);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  assert.deepEqual(training.getSnapshot().workout!.exercises[0].sets.slice(0, 2).map(s => s.equipmentSetupId), [null, null]);
  assert.equal(training.getSnapshot().equipmentSetups.find(s => s.id === a.id)!.archived, false);
});

test('last selection follows the exercise into new occurrences and setup-free remains distinct', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ultra-equipment-'));
  const path = join(directory, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  t.after(async () => { await training.close(); await rm(directory, { recursive: true, force: true }); });
  await training.start();
  const workout = training.getSnapshot().workout!;
  await training.adaptWorkout(workout.id, { type: 'add-exercise', catalogueId: 'lat-pulldown' });
  const first = training.getSnapshot().workout!.exercises[0];
  const setup = await training.createEquipmentSetup({ label: null, gym: null, ratio: null });
  await training.selectEquipmentSetup(first.id, setup.id);
  await training.adaptWorkout(workout.id, { type: 'add-exercise', catalogueId: 'lat-pulldown' });
  let second = training.getSnapshot().workout!.exercises[1];
  assert.equal(second.sets[0].equipmentSetupId, setup.id);
  await training.selectEquipmentSetup(second.id, null);
  await training.adaptWorkout(workout.id, { type: 'add-exercise', catalogueId: 'lat-pulldown' });
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  second = training.getSnapshot().workout!.exercises[1];
  assert.equal(second.sets[0].equipmentSetupId, null);
  assert.equal(training.getSnapshot().workout!.exercises[2].sets[0].equipmentSetupId, null);
  assert.equal(training.getSnapshot().equipmentSetups[0].id, setup.id);
});

test('switch waits for a pending check and a failed switch leaves assignments and drafts intact', async (t) => {
  const { controlCommits } = await import('./node-database');
  const directory = await mkdtemp(join(tmpdir(), 'ultra-equipment-'));
  const path = join(directory, 'training.db');
  const control = controlCommits(await openNodeDatabase(path));
  let training = await openTraining(control.database);
  t.after(async () => { await training.close(); await rm(directory, { recursive: true, force: true }); });
  await training.start(upperStarter);
  const exercise = training.getSnapshot().workout!.exercises[0];
  const setup = await training.createEquipmentSetup({ label: 'Cable', gym: null, ratio: null });
  await training.editSet(exercise.sets[0].id, { load: '40', reps: '6' });
  const hold = control.holdNextCommit();
  const check = training.setPerformed(exercise.sets[0].id, true);
  await hold.entered;
  const selection = training.selectEquipmentSetup(exercise.id, setup.id);
  hold.release();
  await check; await selection;
  assert.deepEqual(training.getSnapshot().workout!.exercises[0].sets.slice(0, 2).map((s) => s.equipmentSetupId), [null, setup.id]);
  await training.editSet(exercise.sets[1].id, { load: '35.' });
  control.failNextCommit();
  await assert.rejects(training.selectEquipmentSetup(exercise.id, null));
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[1].load, '35.');
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[1].equipmentSetupId, setup.id);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  assert.deepEqual(training.getSnapshot().workout!.exercises[0].sets.slice(0, 2).map((s) => s.equipmentSetupId), [null, setup.id]);
});

test('unnamed equipment setups receive distinct durable labels while supplied labels remain unchanged', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ultra-equipment-'));
  const path = join(directory, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  t.after(async () => { await training.close(); await rm(directory, { recursive: true, force: true }); });
  const first = await training.createEquipmentSetup({ label: null, gym: null, ratio: null });
  const second = await training.createEquipmentSetup({ label: '  ', gym: null, ratio: null });
  const named = await training.createEquipmentSetup({ label: 'Cable tower', gym: null, ratio: null });
  assert.ok(first.label);
  assert.ok(second.label);
  assert.notEqual(first.label, second.label);
  assert.equal(named.label, 'Cable tower');
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  assert.deepEqual(training.getSnapshot().equipmentSetups.map((s) => [s.id, s.label]), [[first.id, first.label], [second.id, second.label], [named.id, 'Cable tower']]);
});

test('archived remembered equipment is excluded from new occurrences until restored', async (t) => {
  const directory = await mkdtemp(join(tmpdir(), 'ultra-equipment-'));
  const path = join(directory, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  t.after(async () => { await training.close(); await rm(directory, { recursive: true, force: true }); });
  await training.start();
  const workout = training.getSnapshot().workout!;
  await training.adaptWorkout(workout.id, { type: 'add-exercise', catalogueId: 'lat-pulldown' });
  const first = training.getSnapshot().workout!.exercises[0];
  const setup = await training.createEquipmentSetup({ label: 'Tower', gym: null, ratio: null });
  await training.selectEquipmentSetup(first.id, setup.id);
  await training.archiveEquipmentSetup(setup.id, true);
  await training.adaptWorkout(workout.id, { type: 'add-exercise', catalogueId: 'lat-pulldown' });
  assert.equal(training.getSnapshot().workout!.exercises[1].sets[0].equipmentSetupId, null);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].equipmentSetupId, setup.id);
  assert.equal(training.getSnapshot().workout!.exercises[1].sets[0].equipmentSetupId, null);
  await training.archiveEquipmentSetup(setup.id, false);
  await training.adaptWorkout(workout.id, { type: 'add-exercise', catalogueId: 'lat-pulldown' });
  assert.equal(training.getSnapshot().workout!.exercises[2].sets[0].equipmentSetupId, setup.id);
  await training.discardWorkout(workout.id);
  await training.archiveEquipmentSetup(setup.id, true);
  await training.start(upperStarter);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].equipmentSetupId, null);
});
