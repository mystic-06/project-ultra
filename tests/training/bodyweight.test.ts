test('saving workout bodyweight and fraction rolls back together and can be retried', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-bodyweight-atomic-'));
  const path = join(dir, 'training.db');
  t.after(() => rm(dir, { recursive: true, force: true }));
  const database = await openNodeDatabase(path);
  let failFraction = false;
  let training = await openTraining({ ...database, async run(sql, parameters) { if (failFraction && sql.startsWith('INSERT INTO exercise_fractions')) { failFraction = false; throw new Error('Simulated fraction write failure'); } await database.run(sql, parameters); } });
  await training.setBodyweightSettings({ bodyweight: '70', writeback: true, setupComplete: true });
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'pull-up' });
  const exerciseId = training.getSnapshot().workout!.exercises[0].id;
  failFraction = true;
  await assert.rejects(training.setBodyweightDetails(exerciseId, { bodyweight: '80', fraction: 0.7 }));
  assert.equal(training.getSnapshot().bodyweightSettings.bodyweight, '70');
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  assert.deepEqual([training.getSnapshot().workout!.bodyweight, training.getSnapshot().workout!.exercises[0].bodyweightFraction, training.getSnapshot().bodyweightSettings.bodyweight], ['70', null, '70']);
  await training.setBodyweightDetails(exerciseId, { bodyweight: '80', fraction: 0.7 });
  assert.deepEqual([training.getSnapshot().workout!.bodyweight, training.getSnapshot().workout!.exercises[0].bodyweightFraction, training.getSnapshot().bodyweightSettings.bodyweight], ['80', 0.7, '80']);
  await training.close();
});

test('new and reset sets use exercise bodyweight even when the exercise has no sets', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-bodyweight-sets-'));
  const path = join(dir, 'training.db');
  t.after(() => rm(dir, { recursive: true, force: true }));
  let training = await openTraining(await openNodeDatabase(path));
  await training.setBodyweightSettings({ bodyweight: '80', writeback: false, setupComplete: true });
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'pull-up' });
  let exercise = training.getSnapshot().workout!.exercises[0];
  await training.setExerciseFraction(exercise.id, 0.7);
  await training.adaptWorkout(id, { type: 'remove-set', exerciseId: exercise.id, setId: exercise.sets[0].id });
  await training.adaptWorkout(id, { type: 'add-set', exerciseId: exercise.id });
  exercise = training.getSnapshot().workout!.exercises[0];
  assert.deepEqual([exercise.sets[0].bodyweight, exercise.sets[0].bodyweightLoad, exercise.sets[0].type, exercise.sets[0].targetMin], ['80', 56, 'normal', 0]);
  await training.adaptWorkout(id, { type: 'replace-set', exerciseId: exercise.id, setId: exercise.sets[0].id });
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  exercise = training.getSnapshot().workout!.exercises[0];
  assert.equal(exercise.sets[0].bodyweightLoad, 56);
  await training.adaptWorkout(id, { type: 'replace-exercise', exerciseId: exercise.id, catalogueId: 'assisted-pull-up' });
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].bodyweight, null);
  await training.close();
});

test('queued default writeback and settings patches preserve each other', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-bodyweight-patches-'));
  const path = join(dir, 'training.db');
  t.after(() => rm(dir, { recursive: true, force: true }));
  const training = await openTraining(await openNodeDatabase(path));
  await training.setBodyweightSettings({ bodyweight: '70', writeback: true, setupComplete: true });
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'pull-up' });
  const exercise = training.getSnapshot().workout!.exercises[0];
  await Promise.all([training.setWorkoutBodyweight(exercise.id, '80'), training.setBodyweightSettings({ writeback: false })]);
  assert.deepEqual([training.getSnapshot().bodyweightSettings.bodyweight, training.getSnapshot().bodyweightSettings.writeback], ['80', false]);
  await Promise.all([training.setBodyweightSettings({ writeback: true }), training.setBodyweightSettings({ bodyweight: '90' })]);
  assert.deepEqual([training.getSnapshot().bodyweightSettings.bodyweight, training.getSnapshot().bodyweightSettings.writeback], ['90', true]);
  await training.close();
});

