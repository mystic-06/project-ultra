import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { openTraining } from '../../src/training/workout';
import { openNodeDatabase } from './node-database';

test('assistance requires a valid magnitude, unchecks invalid edits, and preserves its original unit in history', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-assistance-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const path = join(dir, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'assisted-pull-up' });
  const setId = training.getSnapshot().workout!.exercises[0].sets[0].id;
  assert.equal(await training.editSet(setId, { load: '12' }), false);
  await training.editSet(setId, { reps: '8' });
  assert.equal(await training.setPerformed(setId, true), false);
  await training.editSet(setId, { assistance: '0' });
  assert.equal(await training.setPerformed(setId, true), true);
  const save = training.editSet(setId, { assistance: '1.234' });
  assert.deepEqual([training.getSnapshot().workout!.exercises[0].sets[0].performed, training.getSnapshot().workout!.exercises[0].sets[0].assistance], [false, '1.234']);
  await save;
  await assert.rejects(training.setLoadUnit('lb'));
  await training.editSet(setId, { assistance: '10.25' });
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].performed, false);
  assert.equal(await training.setPerformed(setId, true), true);
  await training.setLoadUnit('lb');
  await training.finishWorkout(id);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  const set = (await training.getCompletedWorkout(id))!.exercises[0].sets[0];
  assert.deepEqual([set.originalAssistance, set.assistanceUnit, set.assistance, set.originalLoad, set.loadUnit, set.performed], ['10.25', 'kg', '22.6', '', 'kg', true]);
  await training.close();
});


test('previous assistance copies its measurement and reps with confirmation while preserving effort and check', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-assistance-copy-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const path = join(dir, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'assisted-pull-up' });
  let set = training.getSnapshot().workout!.exercises[0].sets[0];
  await training.editSet(set.id, { assistance: '10.25', reps: '8' });
  await training.setPerformed(set.id, true);
  await training.finishWorkout(id);
  await training.setLoadUnit('lb');
  await training.start();
  const nextId = training.getSnapshot().workout!.id;
  await training.adaptWorkout(nextId, { type: 'add-exercise', catalogueId: 'assisted-pull-up' });
  set = training.getSnapshot().workout!.exercises[0].sets[0];
  assert.deepEqual([set.previous!.assistance, set.previous!.originalAssistance, set.previous!.assistanceUnit], ['22.6', '10.25', 'kg']);
  await training.editSet(set.id, { assistance: '5', reps: '2', rpe: '7' });
  await training.setPerformed(set.id, true);
  set = training.getSnapshot().workout!.exercises[0].sets[0];
  assert.equal(await training.copyPrevious(set.id, false), false);
  assert.equal(await training.copyPrevious(set.id, true, { reference: set.previous!.reference, revision: set.revision }), true);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  set = training.getSnapshot().workout!.exercises[0].sets[0];
  assert.deepEqual([set.assistance, set.originalAssistance, set.assistanceUnit, set.reps, set.rpe, set.performed], ['22.6', '10.25', 'kg', '8', '7', true]);
  await training.close();
});

test('large finite assistance survives conversion, blur, edits, and reopen', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-assistance-large-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const path = join(dir, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'assisted-pull-up' });
  const setId = training.getSnapshot().workout!.exercises[0].sets[0].id;
  const value = '1' + '0'.repeat(308);
  await training.editSet(setId, { assistance: value, reps: '8' });
  assert.equal(await training.setPerformed(setId, true), true);
  await training.setLoadUnit('lb');
  await training.blurSet(setId);
  assert.equal(await training.editSet(setId, { reps: '9' }), true);
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].performed, true);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  const set = training.getSnapshot().workout!.exercises[0].sets[0];
  assert.equal(set.originalAssistance, value);
  assert.equal(set.performed, true);
  assert.match(set.assistance, /^\d+(?:\.\d{1,2})?$/);
  await training.setLoadUnit('kg');
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].assistance, value);
  await training.close();
});

test('bodyweight assistance copies separately from calculated bodyweight', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-body-assist-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const path = join(dir, 'training.db');
  let training = await openTraining(await openNodeDatabase(path));
  await training.setBodyweightSettings({ bodyweight: '80', writeback: false, setupComplete: true });
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'pull-up' });
  const ex = training.getSnapshot().workout!.exercises[0];
  await training.setExerciseFraction(ex.id, 0.7);
  await training.editSet(ex.sets[0].id, { assistance: '15', load: '5', reps: '6' });
  await training.setPerformed(ex.sets[0].id, true);
  await training.finishWorkout(id);
  await training.start();
  const next = training.getSnapshot().workout!.id;
  await training.adaptWorkout(next, { type: 'add-exercise', catalogueId: 'pull-up' });
  const row = training.getSnapshot().workout!.exercises[0].sets[0];
  assert.equal(row.previous!.assistance, '15');
  assert.equal(await training.copyPrevious(row.id, false), true);
  await training.close();
  training = await openTraining(await openNodeDatabase(path));
  const saved = training.getSnapshot().workout!.exercises[0].sets[0];
  assert.deepEqual([saved.assistance, saved.load, saved.reps, saved.bodyweightLoad], ['15', '5', '6', 56]);
  await training.close();
});

test('pasting an oversized conversion as a new raw measurement remains an invalid draft', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-assistance-draft-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const training = await openTraining(await openNodeDatabase(join(dir, 'training.db')));
  await training.start();
  const id = training.getSnapshot().workout!.id;
  await training.adaptWorkout(id, { type: 'add-exercise', catalogueId: 'assisted-pull-up' });
  const setId = training.getSnapshot().workout!.exercises[0].sets[0].id;
  await training.editSet(setId, { assistance: '1' + '0'.repeat(308), reps: '8' });
  await training.setPerformed(setId, true);
  await training.setLoadUnit('lb');
  const projection = training.getSnapshot().workout!.exercises[0].sets[0].assistance;
  await training.setLoadUnit('kg');
  await training.editSet(setId, { assistance: projection });
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].status, 'editing');
  assert.deepEqual([training.getSnapshot().workout!.exercises[0].sets[0].performed, training.getSnapshot().workout!.exercises[0].sets[0].assistance], [false, projection]);
  await training.blurSet(setId);
  await training.editSet(setId, { reps: '9' });
  assert.equal(training.getSnapshot().workout!.exercises[0].sets[0].assistance, projection);
  await assert.rejects(training.setLoadUnit('lb'));
  await training.close();
});
