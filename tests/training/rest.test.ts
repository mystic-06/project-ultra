import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { openTraining } from '../../src/training/workout';
import { upperStarter } from '../../src/training/routines';
import { openNodeDatabase } from './node-database';

test('new checks start rest and recover the deadline after reopening', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-rest-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const path = join(dir, 'training.db');
  let clock = 1000000;
  let training = await openTraining(await openNodeDatabase(path), () => clock);
  await training.start(upperStarter);
  const id = training.getSnapshot().workout!.exercises[0].sets[0].id;
  await training.editSet(id, { load: '40', reps: '6' });
  await training.setPerformed(id, true);
  assert.equal(training.getRestTimer().remainingSeconds, 90);
  clock += 30000;
  await training.close();
  training = await openTraining(await openNodeDatabase(path), () => clock);
  assert.equal(training.getRestTimer().remainingSeconds, 60);
  clock += 61000;
  assert.equal(training.getRestTimer().state, 'finished');
  await training.close();
});

test('override, restart, correction, settings, manual adjustment and skip survive reopening', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'ultra-rest-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const path = join(dir, 'training.db');
  let clock = 1000000;
  let training = await openTraining(await openNodeDatabase(path), () => clock);
  const routine = { ...upperStarter, exercises: upperStarter.exercises.map((e, i) => ({ ...e, restSeconds: i === 0 ? 45 : undefined })) };
  await training.start(routine);
  const [first, second] = training.getSnapshot().workout!.exercises[0].sets;
  await training.editSet(first.id, { load: '40', reps: '6' });
  await training.setPerformed(first.id, true);
  assert.equal(training.getRestTimer().remainingSeconds, 45);
  clock += 10000;
  await training.editSet(first.id, { reps: '7' });
  await training.setPerformed(first.id, true);
  assert.equal(training.getRestTimer().remainingSeconds, 35);
  await training.editSet(second.id, { load: '40', reps: '6' });
  await training.setPerformed(second.id, true);
  assert.equal(training.getRestTimer().remainingSeconds, 45);
  await training.setRestSettings({ automatic: false, defaultSeconds: 120 });
  await training.startRest(30);
  await training.adjustRest(15);
  clock += 5000;
  await training.close();
  training = await openTraining(await openNodeDatabase(path), () => clock);
  assert.deepEqual(training.getSnapshot().restSettings, { automatic: false, defaultSeconds: 120 });
  assert.equal(training.getRestTimer().remainingSeconds, 40);
  const third = training.getSnapshot().workout!.exercises[1].sets[0];
  await training.editSet(third.id, { load: '40', reps: '6' });
  await training.setPerformed(third.id, true);
  assert.equal(training.getRestTimer().remainingSeconds, 40);
  await training.skipRest();
  assert.equal(training.getRestTimer().state, 'idle');
  await training.setRestSettings({ automatic: true, defaultSeconds: 120 });
  const fourth = training.getSnapshot().workout!.exercises[1].sets[1];
  await training.editSet(fourth.id, { load: '40', reps: '6' });
  await training.setPerformed(fourth.id, true);
  assert.equal(training.getRestTimer().remainingSeconds, 120);
  await training.close();
});

test('a failed check does not start rest; retry starts it after commit', async (t) => {
  const { controlCommits } = await import('./node-database');
  const dir = await mkdtemp(join(tmpdir(), 'ultra-rest-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const control = controlCommits(await openNodeDatabase(join(dir, 'training.db')));
  const training = await openTraining(control.database, () => 1000000);
  await training.start(upperStarter);
  const id = training.getSnapshot().workout!.exercises[0].sets[0].id;
  await training.editSet(id, { load: '40', reps: '6' });
  control.failNextCommit();
  assert.equal(await training.setPerformed(id, true), false);
  assert.equal(training.getRestTimer().state, 'idle');
  assert.equal(await training.retrySet(id), true);
  assert.equal(training.getRestTimer().remainingSeconds, 90);
  await training.close();
});
